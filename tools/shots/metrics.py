"""Glyph advances of the addon's three fonts, for the headless screenshots.

Writes tools/shots/metrics.lua: for each font file (media/fonts/), the advance
of every glyph the font has, in em (advance / font size), over the ranges the
addon's text uses. tools/shots/shim.lua measures text with it, so the addon's
own shrink-to-fit and wrapping see the widths the real client would.
Run once from the repo root (the output is committed):
    python tools/shots/metrics.py
"""
import os
from PIL import ImageFont

FONTS = ["AlegreyaSC-Bold.ttf", "PTSans-Regular.ttf", "PTSans-Bold.ttf"]
REF = 1000  # reference size in px
RANGES = [(0x20, 0x7E), (0xA0, 0x17F), (0x2B0, 0x2FF), (0x370, 0x3FF), (0x400, 0x52F),
          (0x2000, 0x206F), (0x20A0, 0x20CF), (0x2100, 0x214F), (0x2190, 0x21FF), (0x2200, 0x22FF),
          (0x2300, 0x23FF), (0x2460, 0x24FF), (0x2500, 0x25FF), (0x2600, 0x26FF), (0x2700, 0x27BF)]


def has_glyph(font, ch, notdef):
    if ch == " " or ch == " ":
        return True
    mask = font.getmask(ch)
    if mask.size[0] == 0:
        return font.getlength(ch) > 0  # an empty glyph with an advance (a space of some kind)
    return bytes(mask) != notdef[0] or mask.size != notdef[1]


def main():
    root = os.path.join(os.path.dirname(__file__), "..", "..")
    out = ["-- Generated by tools/shots/metrics.py: glyph advances in em, by font file and code point.",
           "return {"]
    for name in FONTS:
        font = ImageFont.truetype(os.path.join(root, "media", "fonts", name), REF,
                                  layout_engine=ImageFont.Layout.BASIC)
        nd = font.getmask("\U000F0000")
        notdef = (bytes(nd), nd.size)
        asc, desc = font.getmetrics()
        out.append('  ["%s"] = { ascent = %.4f, descent = %.4f, adv = {' % (name, asc / REF, desc / REF))
        row = []
        for lo, hi in RANGES:
            for cp in range(lo, hi + 1):
                ch = chr(cp)
                if not has_glyph(font, ch, notdef):
                    continue
                row.append("[%d]=%.4f" % (cp, font.getlength(ch) / REF))
                if len(row) == 8:
                    out.append("    " + ", ".join(row) + ",")
                    row = []
        if row:
            out.append("    " + ", ".join(row) + ",")
        out.append("  } },")
    out.append("}")
    with open(os.path.join(os.path.dirname(__file__), "metrics.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
