-- Rules book: why the deal is fair
T["help.fair.title"] = "Why the deal is fair"
T["help.fair.p1"] = "In the card games nobody shuffles the deck alone. Everyone at the table gives one secret number, and the order of the cards comes from all the numbers together. As long as at least one player at the table is honest, nobody can fix the cards."
T["help.fair.example"] = "Ivan and Maria play Santase. Each thinks of a secret number and locks it in a little box. They both put their boxes on the table. Only then does Ivan give his number to Maria, because she deals this hand. Maria puts the two numbers together and the order of the cards comes out of them. Nobody can change their number after that. Their box is already on the table."
T["help.fair.how"] = "The box is a fingerprint of the number. You cannot guess the number from the fingerprint. But later everyone can check that the number is the same."
T["help.fair.verify"] = "After every hand the numbers are shown to everyone. Your addon lays out the deck again by itself and goes through the whole hand: are the cards you got from this deck, and was every move allowed? If it all adds up, below the table it says “verified”. If something does not add up, it says “irregular”. When only your addon can see it, it tells the table. The others see that as a claim under your name, because they cannot check it."
T["help.fair.dealer"] = "One thing you should know: the dealer's addon knows the whole deck of the hand it deals. Otherwise it could not send you your cards. A normal player does not see it. Only a tampered addon could peek, and only when it deals. That is why the deal passes to the next player every hand, and in the end every hand is checked. At a table with a stake this holds in full: play cards for gold with people you trust."
T["help.fair.bad"] = "See “irregular”? Tell the others. Point at the text with the mouse and you will see what exactly does not add up. A hand can also be irregular because the dealer left right at the end without showing the numbers. If the dealer only reloads the game, their addon keeps the deck and the hand goes on. If they leave or their game crashes in the middle of a hand, it is annulled and the next player deals. Below the table it says who annulled it."
T["help.fair.stakes"] = "At a table with a stake nobody plays or rolls for you. In Tic-tac-toe and Backgammon the host plays your move only once your own clock has run out too. In Death Roll there is no automatic roll. If the table still plays or rolls something in your name, your addon contests the debt by itself."
T["help.fair.dice"] = "The backgammon dice are thrown the same way. The host locks in its number. The guest locks in its own and then sends it only to the host. Only then does the host show both, and every addon works out the dice by itself. The host's number does not come out before the guest's has arrived. The guest cannot pick a die. A tampered host addon can still throw alone. That cannot be stopped, but the guest's addon shows it below the table and counts it. At a table with a stake the guest's addon then contests the debt by itself."
T["help.fair.sealed"] = "In Hold'em the numbers are not shown after every hand, only when the table closes. Otherwise the cards of those who gave up would be seen. Until then the line below the table counts the sealed hands. The dealer's addon knows the deck of its hand here too, and the dealer changes with the button."

