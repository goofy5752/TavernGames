local ns = Loader.ns()
local Ledger, View, U, C = ns.Ledger, ns.LedgerView, ns.Util, ns.Const

local I, M, P = "Иван Петров", "Мария Колева", "Петър Иванов"
local NOW = 1700000000
local G1, G2 = "Иван Петров#1700000000/12", "Иван Петров#1700000000/13"

-- A bystander's ledger. add(author, kind, fields, n, at) files an entry of that
-- author got from the author, numbered n (default: the author's next number).
local function book()
  local b = { l = Ledger.new({}, "Свидетел Тихов", function() return NOW end), seq = {} }
  function b.add(author, kind, fields, n, at)
    n = n or (b.seq[author] or 0) + 1
    b.seq[author] = math.max(b.seq[author] or 0, n)
    local e = U.copy(fields)
    e.k, e.i, e.at = kind, Ledger.id(author, n), at or NOW
    local status, body = b.l:add(e, author)
    assert(status == "new" or status == "twin", "add " .. tostring(body))
    return body
  end
  -- A D of `author` (f or t): f owes t c copper for game gid.
  function b.debt(author, f, t, c, gid, n, at)
    return b.add(author, "D", { gid = gid or G1, g = "ttt", f = f, t = t, c = c, why = "lost" }, n, at)
  end
  function b.confirm(author, d) return b.add(author, "C", { r = d.i, dh = d.h }) end
  function b.contest(author, d) return b.add(author, "N", { r = d.i, dh = d.h, why = "no" }) end
  function b.pay(t, f, c) return b.add(t, "P", { f = f, c = c, how = "hand" }) end
  function b.deny(author, e) return b.add(author, "X", { r = e.i, h = e.h }) end
  function b.view() return View.of(b.l) end
  return b
end
local function status(b) return b.view().debts[1].status end

describe("ledger view: debts", function()
  it("a claim alone is pending and in no balance", function()
    local b = book(); b.debt(I, M, I, 50000)
    local v = b.view()
    eq(#v.debts, 1); eq(v.debts[1].status, "pending"); eq(View.net(v, M, I), 0)
    local cl = View.claims(v, M)
    eq(#cl, 1); ok(cl[1] == v.debts[1])
    eq(v.debts[1].key, G1 .. "|" .. M .. "|" .. I); eq(v.debts[1].f, M); eq(v.debts[1].t, I)
    eq(v.debts[1].c, 50000); eq(v.debts[1].clash, false); eq(v.debts[1].said, nil)
  end)
  it("the debtor's C confirms it", function()
    local b = book(); local d = b.debt(I, M, I, 50000); local c = b.confirm(M, d)
    local v = b.view()
    eq(v.debts[1].status, "confirmed"); eq(v.debts[1].said, c.i); eq(View.net(v, M, I), 50000)
    eq(View.accounts(v, M), { { name = I, net = 50000 } })
    eq(View.accounts(v, I), { { name = M, net = -50000 } })
    eq(#View.claims(v, M), 0)
  end)
  it("a C by somebody else counts for nothing", function()
    local b = book(); local d = b.debt(I, M, I, 50000); b.confirm(P, d)
    eq(status(b), "pending")
  end)
  it("the debtor's own D is a confirmed debt", function()
    local b = book(); b.debt(M, M, I, 50000)
    eq(status(b), "confirmed"); eq(View.net(b.view(), M, I), 50000)
  end)
  it("claim and own D of one game are one debt", function()
    local b = book(); b.debt(I, M, I, 50000); local own = b.debt(M, M, I, 50000)
    local v = b.view()
    eq(#v.debts, 1); eq(v.debts[1].c, 50000); eq(#v.debts[1].ids, 2); eq(v.debts[1].said, own.i)
    eq(v.debts[1].clash, false)
  end)
  it("the debtor's amount wins; the clash shows", function()
    local b = book(); b.debt(I, M, I, 50000); b.debt(M, M, I, 10000)
    local v = b.view()
    eq(v.debts[1].c, 10000); eq(v.debts[1].clash, true); eq(View.net(v, M, I), 10000)
  end)
  it("the newest word of the debtor decides", function()
    local b = book(); local d = b.debt(I, M, I, 50000); b.confirm(M, d); local n = b.contest(M, d)
    eq(status(b), "contested"); eq(View.net(b.view(), M, I), 0); eq(b.view().debts[1].said, n.i)
    b = book(); d = b.debt(I, M, I, 50000); b.contest(M, d); b.confirm(M, d)
    eq(status(b), "confirmed"); eq(View.net(b.view(), M, I), 50000)
  end)
  it("a denied claim is no debt", function()
    local b = book(); local d = b.debt(I, M, I, 50000); b.deny(I, d)
    eq(#b.view().debts, 0)
  end)
  it("a denied C un-confirms", function()
    local b = book(); local d = b.debt(I, M, I, 50000); local c = b.confirm(M, d); b.deny(M, c)
    eq(status(b), "pending")
  end)
  it("twins both count", function()
    local b = book(); b.debt(M, M, I, 50000, G1, 1); b.debt(M, M, I, 50000, G2, 1)
    local v = b.view()
    eq(#v.debts, 2); eq(v.debts[1].ids, { M .. ":1" }); eq(v.debts[2].ids, { M .. ":1" })
    eq(v.debts[1].status, "confirmed"); eq(v.debts[2].status, "confirmed"); eq(View.net(v, M, I), 100000)
  end)
  it("a C or N counts only for the D whose hash it names", function()
    local b = book(); local d = b.debt(I, M, I, 50000); b.confirm(M, d)
    b.debt(I, M, I, 5000000, G2, 1)
    local v = b.view()
    eq(#v.debts, 2); eq(v.debts[1].gid, G1); eq(v.debts[1].status, "confirmed"); eq(v.debts[1].c, 50000)
    eq(v.debts[2].gid, G2); eq(v.debts[2].status, "pending"); eq(View.net(v, M, I), 50000)
    b = book(); d = b.debt(I, M, I, 50000); b.confirm(M, d); b.debt(I, M, I, 5000000, G1, 1)
    v = b.view()
    eq(#v.debts, 1); eq(v.debts[1].status, "confirmed"); eq(v.debts[1].c, 50000); eq(v.debts[1].clash, true)
    eq(#v.debts[1].ids, 1); eq(View.net(v, M, I), 50000)
    b = book(); d = b.debt(I, M, I, 50000); b.debt(I, M, I, 50000, G2, 1)
    b.debt(M, M, I, 50000, G1); b.debt(M, M, I, 50000, G2); b.contest(M, d)
    v = b.view()
    eq(v.debts[1].status, "contested"); eq(v.debts[2].status, "confirmed"); eq(View.net(v, M, I), 50000)
    b = book(); d = b.debt(I, M, I, 50000); b.add(M, "C", { r = d.i, dh = string.rep("0", 16) })
    eq(status(b), "pending")
  end)
  it("a twin and a denial of the original never move the debtor's C onto the copy", function()
    local b = book(); local d = b.debt(I, M, I, 50000); b.confirm(M, d)
    b.debt(I, M, I, 5000000, G1, 1); b.deny(I, d)
    local v = b.view()
    eq(#v.debts, 1); eq(v.debts[1].status, "pending"); eq(v.debts[1].c, 5000000); eq(View.net(v, M, I), 0)
    b = book(); d = b.debt(I, M, I, 50000); b.confirm(M, d)
    b.debt(I, M, I, 5000000, G2, 1); b.deny(I, d)
    v = b.view()
    eq(#v.debts, 1); eq(v.debts[1].gid, G2); eq(v.debts[1].status, "pending"); eq(View.net(v, M, I), 0)
  end)
  it("copies with lower hashes that evict the original never inherit the debtor's C", function()
    local function body(c, at)
      return { k = "D", i = I .. ":1", at = at, gid = G1, g = "ttt", f = M, t = I, c = c, why = "lost" }
    end
    local origAt, origH = nil, nil
    for k = 1, 32 do
      local h = Ledger.hash(body(50000, NOW - k))
      if not origH or h > origH then origAt, origH = NOW - k, h end
    end
    local b = book(); local d = b.debt(I, M, I, 50000, G1, 1, origAt); b.confirm(M, d)
    eq(d.h, origH)
    local found, k = 0, 0
    while found < 4 do
      k = k + 1
      if Ledger.hash(body(5000000, NOW - k)) < origH then b.debt(I, M, I, 5000000, G1, 1, NOW - k); found = found + 1 end
    end
    ok(not b.l:has(d.i, d.h), "the original is evicted")
    local v = b.view()
    eq(#v.debts, 1); eq(v.debts[1].status, "pending"); eq(v.debts[1].c, 5000000); eq(View.net(v, M, I), 0)
  end)
  it("debts are oldest first, by the claim's at, then key bytes", function()
    local b = book()
    b.debt(I, M, I, 10000, G2, nil, NOW - 10); b.debt(I, P, I, 10000, G1, nil, NOW - 10); b.debt(I, M, I, 10000, G1, nil, NOW - 20)
    local v = b.view()
    eq(v.debts[1].key, G1 .. "|" .. M .. "|" .. I); eq(v.debts[1].at, NOW - 20)
    eq(v.debts[2].key, G1 .. "|" .. P .. "|" .. I); eq(v.debts[3].key, G2 .. "|" .. M .. "|" .. I)
  end)
end)

describe("ledger view: balances", function()
  local function confirmed(b, f, t, c, gid, at) return b.debt(f, f, t, c, gid, nil, at) end
  it("a payment lowers the gross, never below zero", function()
    local b = book(); confirmed(b, M, I, 50000); b.pay(I, M, 20000)
    eq(View.gross(b.view(), M, I), 30000); eq(View.paid(b.view(), M, I), 20000)
    b.pay(I, M, 90000)
    eq(View.gross(b.view(), M, I), 0); eq(View.net(b.view(), M, I), 0); eq(View.paid(b.view(), M, I), 110000)
  end)
  it("a P counts only for its author as creditor", function()
    local b = book(); confirmed(b, M, I, 50000); b.pay(P, M, 50000)
    eq(View.gross(b.view(), M, I), 50000); eq(View.paid(b.view(), M, I), 0); eq(View.paid(b.view(), M, P), 50000)
  end)
  it("a P beyond the gross stays as the pair's credit", function()
    local b = book(); confirmed(b, M, I, 50000, G1); b.pay(I, M, 90000)
    eq(View.gross(b.view(), M, I), 0)
    confirmed(b, M, I, 30000, G2)
    eq(View.gross(b.view(), M, I), 0); eq(View.net(b.view(), M, I), 0)
    confirmed(b, M, I, 20000, "t/1")
    eq(View.gross(b.view(), M, I), 10000)
  end)
  it("an amount that is no whole copper (tampered saved variables) is no debt and no payment", function()
    local b = book(); local d = confirmed(b, M, I, 50000, G1); local p = b.pay(I, M, 20000)
    d.c, p.c = 25000.5, 1e12
    local v = b.view()
    eq(#v.debts, 0); eq(View.paid(v, M, I), 0)
  end)
  it("a denied P counts for nothing", function()
    local b = book(); confirmed(b, M, I, 50000); local p = b.pay(I, M, 20000); b.deny(I, p)
    eq(View.gross(b.view(), M, I), 50000); eq(View.paid(b.view(), M, I), 0)
    local denied = View.denied(b.view())
    eq(#denied, 1); ok(denied[1] == p)
  end)
  it("mutual debts are netted", function()
    local b = book(); confirmed(b, M, I, 50000, G1); confirmed(b, I, M, 30000, G2)
    local v = b.view()
    eq(View.net(v, M, I), 20000); eq(View.net(v, I, M), -20000)
    eq(View.accounts(v, I), { { name = M, net = -20000 } })
  end)
  it("paying the net settles both", function()
    local b = book(); confirmed(b, M, I, 50000, G1); confirmed(b, I, M, 30000, G2); b.pay(I, M, 20000)
    local v = b.view()
    eq(View.net(v, M, I), 0); eq(View.net(v, I, M), 0); eq(View.accounts(v, M), {})
    local rows = View.rows(v)
    eq(#rows, 2)
    for _, r in ipairs(rows) do eq(r.open, 0) end
  end)
  it("rows: first in, first out", function()
    local b = book(); confirmed(b, M, I, 50000, G1, NOW - 100); confirmed(b, M, I, 30000, G2); b.pay(I, M, 60000)
    local rows = View.rows(b.view())
    eq(rows[1].debt.c, 50000); eq(rows[1].open, 0)
    eq(rows[2].debt.c, 30000); eq(rows[2].open, 20000)
  end)
  it("rows: netting clears the smaller side and the oldest of the larger", function()
    local b = book(); confirmed(b, M, I, 30000, G1, NOW - 100); confirmed(b, M, I, 30000, G2, NOW - 50)
    confirmed(b, I, M, 40000, "t/1")
    local rows = View.rows(b.view())
    eq(rows[1].open, 0); eq(rows[2].open, 20000); eq(rows[3].open, 0)
  end)
  it("rows: pending and contested debts stay whole", function()
    local b = book(); local d = b.debt(I, M, I, 50000, G1); b.debt(I, M, I, 30000, G2); b.contest(M, d)
    b.pay(I, M, 90000)
    local rows = View.rows(b.view())
    eq(rows[1].debt.status, "contested"); eq(rows[1].open, 50000)
    eq(rows[2].debt.status, "pending"); eq(rows[2].open, 30000)
  end)
  it("totals", function()
    local b = book(); confirmed(b, M, I, 50000, G1); confirmed(b, P, I, 20000, G1); b.debt(P, M, P, 10000, G2)
    eq(View.totals(b.view()), { open = 70000, count = 2, top = M, topSum = 50000 })
    eq(View.totals(book().view()), { open = 0, count = 0, topSum = 0 })
  end)
  it("accounts: largest absolute first, then name bytes", function()
    local b = book(); confirmed(b, M, I, 10000, G1); confirmed(b, P, M, 30000, G1); confirmed(b, M, "Ана", 10000, G2)
    eq(View.accounts(b.view(), M), { { name = P, net = -30000 }, { name = "Ана", net = 10000 }, { name = I, net = 10000 } })
  end)
end)

describe("ledger view: claims and the cache", function()
  it("claims are capped per creditor", function()
    local b = book()
    for j = 1, 25 do b.debt(I, M, I, 10000, "t/" .. j, nil, NOW - 100 + j) end
    for j = 1, 3 do b.debt(P, M, P, 10000, "t/" .. j, nil, NOW + j) end
    local v = b.view()
    local cl, mine = View.claims(v, M), 0
    eq(#cl, C.LEDGER_CLAIMS_OPEN + 3)
    for j, d in ipairs(cl) do
      if d.t == I then mine = mine + 1; eq(d.gid, "t/" .. j) end
    end
    eq(mine, 20); eq(cl[#cl].t, P)
    eq(#View.claims(v, I), 0)
  end)
  it("the view is rebuilt only on change", function()
    local b = book(); b.debt(I, M, I, 50000)
    local v = View.of(b.l)
    ok(View.of(b.l) == v)
    b.l:make("P", { f = M, c = 100, how = "hand" })
    local w = View.of(b.l)
    ok(w ~= v); ok(View.of(b.l) == w)
  end)
end)
