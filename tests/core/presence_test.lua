local Sim = require("sim")

local A, B, C, D = "Иван Петров", "Мария Стоянова", "Kiro Barley", "Пешо Тодоров"

describe("presence", function()
  it("newcomer learns everyone by whisper, not by a guild burst", function()
    local sim = Sim.new(); sim:add("Иван Петров", {cls="MAGE"}); sim:add("Мария Стоянова", {cls="PRIEST"}); sim:run(1)
    local n0 = sim:count(function(m) return m.channel == "GUILD" end)
    local c = sim:add("Kiro Barley", {cls="ROGUE"}); sim:run(1)
    eq(#c.presence:list(), 2); eq(c.presence:get("Иван Петров").cls, "MAGE")
    eq(sim:count(function(m) return m.channel == "GUILD" end) - n0, 1)
  end)

  it("lists peers sorted by name bytes with their fields", function()
    local sim = Sim.new(); local a = sim:add(A, {cls="MAGE"}); local _, envB = sim:add(B, {cls="PRIEST"})
    sim:add(C, {cls="ROGUE"}); sim:run(1)
    local list = a.presence:list()
    eq(#list, 2); eq(list[1].name, C); eq(list[2].name, B)
    eq(list[2], {name=B, cls="PRIEST", guid=envB.guid, at=nil, incompatible=false})
  end)

  it("drops a peer on BYE, on peerOffline and after 300 s of silence", function()
    local sim = Sim.new()
    local a = sim:add(A, {cls="MAGE"}); local b = sim:add(B, {cls="PRIEST"})
    sim:add(C, {cls="ROGUE"}); sim:add(D, {cls="WARRIOR"}); sim:run(1)
    ok(a.presence:get(B)); ok(a.presence:get(C)); ok(a.presence:get(D))
    sim:offline(D); sim:run(301)
    eq(a.presence:get(D), nil); ok(a.presence:get(B)); ok(a.presence:get(C))
    b:stop(); sim:run(1); eq(a.presence:get(B), nil)
    a:peerOffline(C); eq(a.presence:get(C), nil); eq(#a.presence:list(), 0)
  end)

  it("keeps a quiet peer alive through the 120 s guild heartbeat", function()
    local sim = Sim.new(); local a = sim:add(A, {cls="MAGE"}); sim:add(B, {cls="PRIEST"}); sim:run(1)
    local n0 = sim:count(function(m) return m.from == B and m.channel == "GUILD" end)
    sim:run(600)
    ok(a.presence:get(B))
    eq(sim:count(function(m) return m.from == B and m.channel == "GUILD" end) - n0, 5)
    eq(sim:count(function(m) return m.from == B and m.channel == "GUILD" and m.msg.re == true end), 1)
  end)

  it("emits peers on change", function()
    local sim = Sim.new(); local a = sim:add(A, {cls="MAGE"})
    local seen = 0; a:on("peers", function() seen = seen + 1 end)
    sim:add(B, {cls="PRIEST"}); sim:run(1); eq(seen, 1)
    sim:run(120); eq(seen, 1)
    a:peerOffline(B); eq(seen, 2)
  end)

  it("announces its own seat change on GUILD, at most one HI per 2 s", function()
    local sim = Sim.new(); local a = sim:add(A, {cls="MAGE"}); local b = sim:add(B, {cls="PRIEST"}); sim:run(5)
    local function hiFromA() return sim:count(function(m) return m.from == A and m.channel == "GUILD" and m.msg.t == "HI" end) end
    local n0 = hiFromA()
    a.presence:setAt("X#1"); a.presence:setAt(nil); a.presence:setAt("Y#2")
    eq(hiFromA() - n0, 1)
    sim:run(1); eq(hiFromA() - n0, 1)
    sim:run(1); eq(hiFromA() - n0, 2); eq(b.presence:get(A).at, "Y#2")
    sim:run(10); eq(hiFromA() - n0, 2)
  end)

  it("flags a newer protocol once and lists the peer as incompatible", function()
    local sim = Sim.new(); local a = sim:add(A, {cls="MAGE"})
    local seen = 0; a:on("update", function() seen = seen + 1 end)
    a:receive("GUILD", "Нов Клиент", {v=2, t="HI"}); a:receive("GUILD", "Нов Клиент", {v=2, t="ZZZ"})
    eq(seen, 1); eq(a.presence:get("Нов Клиент").incompatible, true)
    a:receive("GUILD", "Стар Клиент", {v=0, t="HI"})
    eq(seen, 1); eq(a.presence:get("Стар Клиент").incompatible, true)
  end)

  it("ignores garbage: a string, a table without t, its own name", function()
    local sim = Sim.new(); local a = sim:add(A, {cls="MAGE"})
    a:receive("GUILD", "Гошо Тестов", "hello"); a:receive("GUILD", "Гошо Тестов", {v=1})
    a:receive("GUILD", A, {v=1, t="HI", cls="MAGE"})
    eq(a.presence:get("Гошо Тестов"), nil); eq(a.presence:get(A), nil); eq(#a.presence:list(), 0)
  end)

  it("stop sends BYE and silences every timer", function()
    local sim = Sim.new(); local a = sim:add(A, {cls="MAGE"}); sim:add(B, {cls="PRIEST"}); sim:run(1)
    a:stop()
    eq(sim:count(function(m) return m.from == A and m.msg.t == "BYE" and m.channel == "GUILD" end), 1)
    local n0 = sim:count(function(m) return m.from == A end)
    sim:run(600); eq(sim:count(function(m) return m.from == A end), n0)
  end)

  it("sim: offline drops both ways, relog gives a fresh client", function()
    local sim = Sim.new(); local a = sim:add(A, {cls="MAGE"}); sim:add(B, {cls="PRIEST"})
    sim:offline(B); sim:run(1)
    eq(a.presence:get(B), nil)
    sim:online(B); local b2 = sim:relog(B); sim:run(1)
    ok(a.presence:get(B)); eq(b2.presence:get(A).cls, "MAGE")
    local s = sim.sent[1]; eq(s.at, 0); eq(s.from, A); eq(s.channel, "GUILD"); eq(s.msg.t, "HI")
  end)
end)
